// esbuild options for the backend: web/server → app/_service.js, one ES
// module. Not minified, so what Yard runs stays readable in the repo;
// Orbit's own code is at the end, after the bundled zod.
export const serverBuild = {
  entryPoints: ["server/index.ts"],
  outfile: "../app/_service.js",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  legalComments: "none",
  logLevel: "info",
  banner: { js: "// GENERATED by web/scripts/build.mjs from web/server. Do not edit; rebuild instead." },
  plugins: [englishOnlyZod()],
};

// zod re-exports every locale it ships (~350 KB); the service only ever
// speaks English, so the locale index resolves to English alone.
function englishOnlyZod() {
  return {
    name: "english-only-zod",
    setup(build) {
      build.onResolve({ filter: /\/locales\/index\.js$/ }, (args) =>
        args.importer.includes("/zod/") ? { path: "zod-locales", namespace: "zod-locales" } : undefined,
      );
      build.onLoad({ filter: /.*/, namespace: "zod-locales" }, () => ({
        contents: 'export { default as en } from "zod/v4/locales/en.js";',
        resolveDir: process.cwd(),
      }));
    },
  };
}
